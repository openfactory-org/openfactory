// Package codex implements the Codex CLI harness: it runs `codex exec --json` in the run's
// sandbox and translates the JSONL event stream into core.HarnessEvents.
//
// Invocation (one process per turn; the prompt is written to stdin via the "-" argument):
//
//	codex exec [resume] --json --skip-git-repo-check --dangerously-bypass-approvals-and-sandbox
//	           [-m <model>] [-c model_reasoning_effort="<level>"] [-C <workdir>] [<thread_id>] -
//
// Configuration is isolated per run: CODEX_HOME points at <workdir>/.openfactory/codex, which holds
// config.toml (MCP servers as [mcp_servers.<name>] tables, shell environment policy), AGENTS.md
// (the composed system prompt, read by Codex as global instructions without touching the
// repository's own AGENTS.md) and skills/<name>/SKILL.md. Session files also live there, so
// `codex exec resume <thread_id>` works for follow-ups in the same sandbox.
package codex

import (
	"context"
	"encoding/json"
	"fmt"
	"log/slog"
	"maps"
	"slices"
	"strings"
	"time"

	"github.com/openfactory-org/openfactory/internal/core"
	"github.com/openfactory-org/openfactory/internal/harness"
)

// HomeDir is CODEX_HOME relative to the work dir.
const HomeDir = harness.StateDir + "/codex"

// Options configures the harness.
type Options struct {
	// Binary is the CLI executable (default "codex").
	Binary string
	// FullAuto uses --full-auto (workspace-write sandbox, no approvals) instead of
	// --dangerously-bypass-approvals-and-sandbox. Use when the sandbox supports Codex's own
	// seccomp/landlock sandboxing; disposable container sandboxes normally do not need it.
	FullAuto bool
	// Config holds extra `-c key=value` overrides (value is raw TOML).
	Config map[string]string
	// ExtraArgs are appended before the prompt argument.
	ExtraArgs []string
	// ExtraEnv is merged last into the process environment.
	ExtraEnv map[string]string
	// Timeout bounds one turn (0 = no limit beyond ctx).
	Timeout time.Duration
	Logger  *slog.Logger
}

// Harness is the Codex harness.
type Harness struct{ opts Options }

// New returns a Codex harness.
func New(opts Options) *Harness {
	if opts.Binary == "" {
		opts.Binary = "codex"
	}
	if opts.Logger == nil {
		opts.Logger = slog.Default()
	}
	return &Harness{opts: opts}
}

// Type implements core.Harness.
func (h *Harness) Type() core.HarnessType { return core.HarnessCodex }

// ReasoningEffort maps a reasoningLevel to Codex's model_reasoning_effort.
func ReasoningEffort(level string) string {
	switch l := strings.ToLower(strings.TrimSpace(level)); l {
	case "minimal", "low", "medium", "high", "xhigh":
		return l
	case "max":
		return "xhigh"
	case "none":
		return "minimal"
	}
	return ""
}

func resolveModel(model string) string {
	m := strings.TrimSpace(model)
	switch strings.ToLower(m) {
	case "", "default":
		return ""
	}
	return strings.TrimPrefix(m, "openai/")
}

// BuildArgs returns argv for one turn.
func (h *Harness) BuildArgs(req core.HarnessRequest, workDir string) []string {
	var cfg core.HarnessConfig
	if req.Run != nil {
		cfg = req.Run.Config.Harness
	}
	resume := req.Resume && req.Run != nil && req.Run.SessionID != ""
	args := []string{h.opts.Binary, "exec"}
	if resume {
		args = append(args, "resume")
	}
	args = append(args, "--json", "--skip-git-repo-check")
	if h.opts.FullAuto {
		args = append(args, "--full-auto")
	} else {
		args = append(args, "--dangerously-bypass-approvals-and-sandbox")
	}
	if m := resolveModel(cfg.Model); m != "" {
		args = append(args, "-m", m)
	}
	if e := ReasoningEffort(cfg.ReasoningLevel); e != "" {
		args = append(args, "-c", "model_reasoning_effort="+harness.TOMLString(e))
	}
	for _, k := range sortedKeys(h.opts.Config) {
		args = append(args, "-c", k+"="+h.opts.Config[k])
	}
	if !resume && workDir != "" {
		args = append(args, "-C", workDir)
	}
	args = append(args, h.opts.ExtraArgs...)
	if resume {
		args = append(args, req.Run.SessionID)
	}
	return append(args, "-")
}

func sortedKeys(m map[string]string) []string { return slices.Sorted(maps.Keys(m)) }

// ConfigTOML renders the per-run config.toml.
func ConfigTOML(servers map[string]core.MCPServer) (string, []string) {
	var b strings.Builder
	b.WriteString("# Generated by Open Factory for this run.\n")
	b.WriteString("[shell_environment_policy]\ninherit = \"all\"\nignore_default_excludes = true\nexclude = [\"OPENAI_API_KEY\", \"CODEX_API_KEY\"]\n\n")
	mcp, warnings := harness.CodexMCPConfigTOML(servers)
	b.WriteString(mcp)
	return b.String(), warnings
}

// Run implements core.Harness.
func (h *Harness) Run(ctx context.Context, sb core.Sandbox, req core.HarnessRequest) (<-chan core.HarnessEvent, error) {
	workDir := harness.WorkDir(sb, req)
	authEnv, err := harness.CodexAuthEnv(req.Auth)
	if err != nil {
		return nil, fmt.Errorf("codex auth: %w", err)
	}
	if err := harness.EnsureStateDir(ctx, sb, workDir); err != nil {
		return nil, fmt.Errorf("prepare sandbox: %w", err)
	}
	home := harness.ResolvePath(workDir, HomeDir)
	cfg, logs := ConfigTOML(req.MCPServers)
	if err := harness.WriteFile(ctx, sb, home+"/config.toml", []byte(cfg), 0o600); err != nil {
		return nil, fmt.Errorf("write codex config: %w", err)
	}
	// The CLI reads AGENTS.md of the work directory itself. The other
	// rule files and the skill directories of the repositories are added
	// here, so each harness gets the same instructions.
	repo := harness.DiscoverRepo(ctx, sb, workDir)
	req.Skills = harness.MergeRepoSkills(req.Skills, repo.Skills)
	instructions := strings.TrimSpace(req.SystemPrompt)
	if instr := harness.RepoInstructions(repo.Rules, harness.RootFile("AGENTS.md")); instr != "" {
		instructions = strings.TrimSpace(instructions + "\n\n" + instr)
	}
	if len(req.Skills) > 0 {
		if _, err := harness.WriteSkills(ctx, sb, workDir, req.Skills, harness.SkillWriteOptions{Dirs: []string{harness.SkillsDir, HomeDir + "/skills"}}); err != nil {
			return nil, err
		}
		instructions = strings.TrimSpace(instructions + "\n\nSkill files are available under `" + harness.SkillsDir + "/<name>/SKILL.md` (with supporting files). Read a skill before following it.")
	}
	if err := harness.WriteFile(ctx, sb, home+"/AGENTS.md", []byte(instructions+"\n"), 0o644); err != nil {
		return nil, fmt.Errorf("write instructions: %w", err)
	}
	args := h.BuildArgs(req, workDir)
	env := harness.MergeEnv(req.Env, authEnv, map[string]string{
		"CODEX_HOME": home,
		"NO_COLOR":   "1",
		"RUST_LOG":   "error",
	}, h.opts.ExtraEnv)
	model := ""
	if req.Run != nil {
		model = resolveModel(req.Run.Config.Harness.Model)
	}

	em, ch := harness.NewEmitter(ctx)
	go func() {
		defer em.Close()
		for _, l := range logs {
			em.Log("%s", l)
		}
		runCtx := ctx
		if h.opts.Timeout > 0 {
			var cancel context.CancelFunc
			runCtx, cancel = context.WithTimeout(ctx, h.opts.Timeout)
			defer cancel()
		}
		p := newParser(model)
		if req.Resume && req.Run != nil {
			p.threadID = req.Run.SessionID
		}
		start := time.Now()
		res, err := harness.StreamLines(runCtx, sb, core.ExecRequest{Cmd: args, Dir: workDir, Env: env}, req.Prompt, func(line []byte) {
			for _, ev := range p.handle(line) {
				em.Emit(ev)
			}
		})
		if p.finished {
			return
		}
		var msg string
		switch {
		case err != nil:
			msg = fmt.Sprintf("codex: %v", err)
		case p.lastError != "":
			msg = "codex: " + p.lastError
		case res.ExitCode != 0:
			msg = fmt.Sprintf("codex exited with code %d", res.ExitCode)
		default:
			msg = "codex exited without completing the turn"
		}
		if tail := harness.LastLines(res.Stderr, 20); tail != "" {
			msg += ": " + tail
		}
		msg += harness.CredentialHint(req)
		h.opts.Logger.Warn("codex harness failed", "sandbox", sb.ID(), "error", msg, "elapsed", time.Since(start))
		em.Emit(core.HarnessEvent{Kind: harness.EventError, Content: msg, SessionID: p.threadID})
	}()
	return ch, nil
}

type parser struct {
	model     string
	threadID  string
	lastText  string
	lastError string
	started   map[string]bool
	finished  bool
	start     time.Time
}

func newParser(model string) *parser {
	return &parser{model: model, started: map[string]bool{}, start: time.Now()}
}

type event struct {
	Type     string          `json:"type"`
	ThreadID string          `json:"thread_id"`
	Item     json.RawMessage `json:"item"`
	Usage    *struct {
		InputTokens       int64 `json:"input_tokens"`
		CachedInputTokens int64 `json:"cached_input_tokens"`
		OutputTokens      int64 `json:"output_tokens"`
	} `json:"usage"`
	Error   *struct{ Message string } `json:"error"`
	Message string                    `json:"message"`
}

type item struct {
	ID               string          `json:"id"`
	Type             string          `json:"type"`
	Text             string          `json:"text"`
	Command          string          `json:"command"`
	AggregatedOutput string          `json:"aggregated_output"`
	ExitCode         *int            `json:"exit_code"`
	Status           string          `json:"status"`
	Server           string          `json:"server"`
	Tool             string          `json:"tool"`
	Arguments        json.RawMessage `json:"arguments"`
	Result           *struct {
		Content           []map[string]any `json:"content"`
		StructuredContent any              `json:"structured_content"`
	} `json:"result"`
	Error *struct {
		Message string `json:"message"`
	} `json:"error"`
	Changes []struct {
		Path string `json:"path"`
		Kind string `json:"kind"`
	} `json:"changes"`
	Query   string `json:"query"`
	Message string `json:"message"`
	Items   []struct {
		Text      string `json:"text"`
		Completed bool   `json:"completed"`
	} `json:"items"`
}

func (p *parser) handle(line []byte) []core.HarnessEvent {
	var ev event
	if err := json.Unmarshal(line, &ev); err != nil || ev.Type == "" {
		return []core.HarnessEvent{{Kind: harness.EventLog, Role: "log", Content: harness.Truncate(string(line), 4000)}}
	}
	switch ev.Type {
	case "thread.started":
		if ev.ThreadID != "" {
			p.threadID = ev.ThreadID
		}
		return []core.HarnessEvent{{Kind: harness.EventSession, SessionID: p.threadID}}
	case "item.started", "item.updated", "item.completed":
		var it item
		if json.Unmarshal(ev.Item, &it) != nil {
			return nil
		}
		return p.item(ev.Type, it)
	case "turn.completed":
		p.finished = true
		u := &core.Usage{DurationMS: time.Since(p.start).Milliseconds()}
		if ev.Usage != nil {
			u.InputTokens = ev.Usage.InputTokens
			u.OutputTokens = ev.Usage.OutputTokens
			u.CostUSD = estimateCost(p.model, ev.Usage.InputTokens, ev.Usage.CachedInputTokens, ev.Usage.OutputTokens)
		}
		return []core.HarnessEvent{
			{Kind: harness.EventUsage, Usage: u, SessionID: p.threadID},
			{Kind: harness.EventDone, Role: "assistant", Content: p.lastText, SessionID: p.threadID, Usage: u},
		}
	case "turn.failed":
		p.finished = true
		msg := "turn failed"
		if ev.Error != nil && ev.Error.Message != "" {
			msg = ev.Error.Message
		}
		return []core.HarnessEvent{{Kind: harness.EventError, Content: "codex: " + msg, SessionID: p.threadID}}
	case "error":
		msg := ev.Message
		if msg == "" && ev.Error != nil {
			msg = ev.Error.Message
		}
		p.lastError = msg
		return []core.HarnessEvent{{Kind: harness.EventLog, Role: "log", Content: "codex error: " + msg}}
	}
	return nil // turn.started and unknown future event types
}

func (p *parser) toolCall(it item, name string, input any) core.HarnessEvent {
	p.started[it.ID] = true
	in, _ := json.Marshal(input)
	return core.HarnessEvent{
		Kind: harness.EventToolCall, Role: "tool_call", SessionID: p.threadID,
		Content: name + " " + harness.Truncate(string(in), 2000),
		Data:    map[string]any{"id": it.ID, "name": name, "input": input, "item_type": it.Type},
	}
}

func (p *parser) toolResult(it item, name, content string, isError bool, extra map[string]any) core.HarnessEvent {
	d := map[string]any{"tool_use_id": it.ID, "name": name, "is_error": isError, "item_type": it.Type}
	for k, v := range extra {
		d[k] = v
	}
	return core.HarnessEvent{Kind: harness.EventToolResult, Role: "tool_result", Content: harness.Truncate(content, 16000), SessionID: p.threadID, Data: d}
}

func (p *parser) item(phase string, it item) []core.HarnessEvent {
	var name string
	var input any
	switch it.Type {
	case "command_execution":
		name, input = "shell", map[string]any{"command": it.Command}
	case "mcp_tool_call":
		name = "mcp__" + it.Server + "__" + it.Tool
		var args any
		_ = json.Unmarshal(it.Arguments, &args)
		input = args
	case "file_change":
		name = "apply_patch"
		input = map[string]any{"changes": it.Changes}
	case "web_search":
		name, input = "web_search", map[string]any{"query": it.Query}
	}

	if phase == "item.started" {
		if name != "" {
			return []core.HarnessEvent{p.toolCall(it, name, input)}
		}
		return nil
	}
	if phase == "item.updated" {
		return nil
	}

	var evs []core.HarnessEvent
	if name != "" && !p.started[it.ID] {
		evs = append(evs, p.toolCall(it, name, input))
	}
	switch it.Type {
	case "agent_message":
		if strings.TrimSpace(it.Text) != "" {
			p.lastText = it.Text
			evs = append(evs, core.HarnessEvent{Kind: harness.EventMessage, Role: "assistant", Content: it.Text, SessionID: p.threadID})
		}
	case "command_execution":
		code := 0
		if it.ExitCode != nil {
			code = *it.ExitCode
		}
		isErr := code != 0 || it.Status == "failed" || it.Status == "declined"
		evs = append(evs, p.toolResult(it, name, it.AggregatedOutput, isErr, map[string]any{"exit_code": code}))
	case "mcp_tool_call":
		if it.Error != nil && it.Error.Message != "" {
			evs = append(evs, p.toolResult(it, name, it.Error.Message, true, nil))
		} else {
			evs = append(evs, p.toolResult(it, name, mcpResultText(it), it.Status == "failed", nil))
		}
	case "file_change":
		var parts []string
		for _, c := range it.Changes {
			parts = append(parts, c.Kind+" "+c.Path)
		}
		evs = append(evs, p.toolResult(it, name, strings.Join(parts, "\n"), it.Status == "failed", nil))
	case "web_search":
		evs = append(evs, p.toolResult(it, name, "searched: "+it.Query, false, nil))
	case "todo_list":
		var b strings.Builder
		for _, t := range it.Items {
			mark := "[ ]"
			if t.Completed {
				mark = "[x]"
			}
			b.WriteString(mark + " " + t.Text + "\n")
		}
		evs = append(evs, core.HarnessEvent{Kind: harness.EventLog, Role: "log", Content: "plan:\n" + b.String(), Data: map[string]any{"item_type": "todo_list"}})
	case "error":
		msg := it.Message
		if msg == "" {
			msg = it.Text
		}
		evs = append(evs, core.HarnessEvent{Kind: harness.EventLog, Role: "log", Content: "codex error: " + msg})
	}
	return evs
}

func mcpResultText(it item) string {
	if it.Result == nil {
		return ""
	}
	var parts []string
	for _, c := range it.Result.Content {
		switch c["type"] {
		case "text":
			if s, ok := c["text"].(string); ok {
				parts = append(parts, s)
			}
		case "image":
			parts = append(parts, "[image]")
		default:
			b, _ := json.Marshal(c)
			parts = append(parts, string(b))
		}
	}
	if len(parts) == 0 && it.Result.StructuredContent != nil {
		b, _ := json.Marshal(it.Result.StructuredContent)
		parts = append(parts, string(b))
	}
	return strings.Join(parts, "\n")
}

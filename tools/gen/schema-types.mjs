#!/usr/bin/env node
// Writes TypeScript types for every *.json JSON Schema in <schemaDir> to <outDir>,
// one <name>.ts per schema plus index.ts. Usage:
//   node tools/gen/schema-types.mjs schemas/runner/v1 packages/runner-proto/src/generated
// A missing schema directory is not an error (the schemas may not exist yet).
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { readFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const [schemaDir, outDir] = process.argv.slice(2);
if (!schemaDir || !outDir) {
  console.error("usage: schema-types.mjs <schemaDir> <outDir>");
  process.exit(2);
}
if (!existsSync(schemaDir)) {
  console.warn(`schema-types: ${schemaDir} does not exist; nothing to generate`);
  process.exit(0);
}

const banner = `// Generated by tools/gen/schema-types.mjs from ${schemaDir}. Do not edit.`;
const files = readdirSync(schemaDir)
  .filter((f) => f.endsWith(".json"))
  .sort();
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
const modules = [];
for (const f of files) {
  const name = basename(f, ".json").replace(/\.schema$/, "");
  const raw = JSON.parse(readFileSync(join(schemaDir, f), "utf8"));
  // A schema that is only a container of $defs gets a synthetic root that
  // references every definition, so that each one becomes an exported type.
  const defsOnly = raw.$defs && !raw.type && !raw.properties && !raw.oneOf && !raw.anyOf && !raw.allOf && !raw.$ref;
  const schema = defsOnly
    ? {
        ...raw,
        title: `${name.replace(/(^|[-_])([a-z])/g, (_, __, c) => c.toUpperCase())}Definitions`,
        type: "object",
        properties: Object.fromEntries(Object.keys(raw.$defs).map((k) => [k, { $ref: `#/$defs/${k}` }])),
        additionalProperties: false,
      }
    : raw;
  const ts = await compile(schema, name, {
    cwd: resolve(schemaDir),
    bannerComment: banner,
    additionalProperties: false,
    strictIndexSignatures: true,
    unknownAny: true,
    format: true,
    style: { printWidth: 120, singleQuote: false, trailingComma: "all" },
  });
  const mod = name.replace(/[^a-zA-Z0-9_-]/g, "_");
  writeFileSync(join(outDir, `${mod}.ts`), ts);
  modules.push(mod);
}
// index.ts: every module as a namespace, plus flat exports of names that are unique across modules.
const names = new Map();
for (const m of modules) {
  const src = readFileSync(join(outDir, `${m}.ts`), "utf8");
  for (const [, n] of src.matchAll(/^export (?:interface|type) ([A-Za-z0-9_]+)/gm)) {
    names.set(n, [...(names.get(n) ?? []), m]);
  }
}
const lines = [banner];
for (const m of modules) {
  const ns = m.replace(/[-]/g, "_");
  const unique = [...names].filter(([, ms]) => ms.length === 1 && ms[0] === m).map(([n]) => n);
  lines.push(`export type * as ${ns} from "./${m}";`);
  if (unique.length > 0) lines.push(`export type { ${unique.join(", ")} } from "./${m}";`);
}
writeFileSync(join(outDir, "index.ts"), lines.join("\n") + "\n");
console.log(`schema-types: ${files.length} schema(s) -> ${outDir}`);

// Route metadata of the REST API: every operation of api/openapi.json, its
// method, path and minimum role. No handlers: TeamDO and other modules read
// this table without loading the handlers of src/api/. src/http/routes.ts
// binds a handler to each operationId; test/routes.test.ts checks the table
// against api/openapi.json.
//
// To add a route: edit api/openapi.json, run `npm run gen:api`, add the row
// here and its handler in src/http/routes.ts.
import type { Role } from "./do-messages";

/** Minimum role of a route ("public": no authentication; "worker": worker access token). */
